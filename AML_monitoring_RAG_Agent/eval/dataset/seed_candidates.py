import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
OUTPUT_CANDIDATES = PROJECT_ROOT / "eval" / "dataset" / "candidates.jsonl"
OUTPUT_CANDIDATES.parent.mkdir(parents=True, exist_ok=True)

# 25 Unanswerable Queries (Questions about regulations absent from FATF/KB)
UNANSWERABLE_QUERIES = [
    "What are the specific tax filing penalties under Section 452 of the Swiss Banking Act?",
    "How does the 2025 EU MiCA regulation classify algorithmic stablecoin collateral ratios?",
    "What is the exact maximum wire transfer fee permitted by the Reserve Bank of India?",
    "What are the mandatory KYC exemption limits for prepaid transit cards in Japan?",
    "Under FATF Recommendation 45, what is the criminal penalty for non-reporting of cash in Canada?",
    "What are the specific beneficial ownership disclosure rules for Jersey island trusts?",
    "How does Singapore MAS Regulation 712 define decentralized autonomous organization (DAO) governance liability?",
    "What is the maximum allowable cash withdrawal limit at ATMs in Dubai Free Zones?",
    "What are the reporting deadlines for suspicious real estate purchases in Liechtenstein?",
    "Under FATF Recommendation 42, what is the threshold for mandatory reporting of diamond exports?",
    "What are the AML licensing requirements for peer-to-peer crypto mixers in Panama?",
    "What is the statutory limitation period for prosecution of trade-based money laundering in Brazil?",
    "What are the specific record-retention requirements for credit unions in New Zealand?",
    "How does the South African Financial Intelligence Centre define high-risk PEP family members in private aviation?",
    "What are the precise compliance rules for sovereign wealth fund investments in real estate in Norway?",
    "Under FATF Recommendation 44, what are the AML audit requirements for casino junket operators?",
    "What is the threshold for mandatory currency declaration when crossing the border into South Korea?",
    "What are the specific customer due diligence rules for virtual metaverse land purchases in the UK?",
    "What are the disclosure penalties for shell company beneficial owners in the Cayman Islands under Law 99?",
    "Under FATF Recommendation 48, what is the mandatory holding period for suspicious wire transfers in Australia?",
    "What are the specific AML rules governing central bank digital currency (CBDC) offline wallets?",
    "What is the maximum allowed transaction limit for unregistered mobile money agents in Kenya?",
    "What are the precise AML compliance steps required for luxury watch auctions in Geneva?",
    "Under FATF Recommendation 50, how are automated smart contract escrow services audited?",
    "What is the exact penalty for failure to verify ultimate beneficial ownership in Hong Kong under Cap 615?",
]

ANSWERABLE_CANDIDATES = [
    ("What are the red flags for structuring in cash deposits?", "threshold_rule", "easy"),
    ("How is cryptocurrency and bitcoin used in money laundering layering?", "typology_lookup", "medium"),
    ("What indicators suggest high risk wire transfers across offshore shell companies?", "typology_lookup", "medium"),
    ("When should a Suspicious Activity Report (SAR) be filed for smurfing?", "threshold_rule", "easy"),
    ("What are common layering techniques in trade-based money laundering?", "typology_lookup", "hard"),
    ("What customer due diligence (CDD) measures are required by FATF for high-risk accounts?", "typology_lookup", "medium"),
    ("What is the record retention period recommended by FATF for transaction logs?", "threshold_rule", "easy"),
    ("How are shell companies utilized to disguise ultimate beneficial ownership?", "typology_lookup", "medium"),
    ("What features distinguish smurfing from routine retail deposits?", "transaction_triage", "medium"),
    ("What wire transfer threshold triggers enhanced monitoring under FATF guidance?", "threshold_rule", "easy"),
]


def generate_candidates():
    candidates = []
    q_count = 1

    # 1. Answerable Candidates
    for text, qtype, diff in ANSWERABLE_CANDIDATES:
        candidates.append({
            "query_id": f"AMLFAITH-{q_count:03d}",
            "query_text": text,
            "query_type": qtype,
            "difficulty": diff,
            "gold_passage_ids": [],  # MUST BE POPULATED BY HUMAN ANNOTATOR
            "reference_answer": "",
            "answerable": True,
            "expected_abstention": False,
            "status": "UNVERIFIED",
            "notes": "Candidate generated by seeding script.",
        })
        q_count += 1

    # 2. 25 Unanswerable Candidates
    for text in UNANSWERABLE_QUERIES:
        candidates.append({
            "query_id": f"AMLFAITH-{q_count:03d}",
            "query_text": text,
            "query_type": "unanswerable",
            "difficulty": "hard",
            "gold_passage_ids": [],
            "reference_answer": "I do not have enough evidence in the regulatory corpus to answer this question confidently.",
            "answerable": False,
            "expected_abstention": True,
            "status": "UNVERIFIED",
            "notes": "Unanswerable query to test abstention accuracy.",
        })
        q_count += 1

    with open(OUTPUT_CANDIDATES, "w", encoding="utf-8") as f:
        for item in candidates:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")

    print(f"Generated {len(candidates)} query candidates in: {OUTPUT_CANDIDATES}")
    print(f"Includes {len(UNANSWERABLE_QUERIES)} unanswerable queries for abstention testing.")


if __name__ == "__main__":
    generate_candidates()
